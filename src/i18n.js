const LOCALES = { hu: 'hu-HU', en: 'en-GB' };
const listeners = [];

function detectLanguage() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (LANGUAGES.includes(saved)) return saved;
  } catch { /* storage blocked */ }
  const nav = (navigator.languages && navigator.languages[0]) || navigator.language || '';
  return nav.toLowerCase().startsWith('hu') ? 'hu' : 'en';
}

let current = detectLanguage();

export function getLanguage() { return current; }

// Locale for number formatting (e.g. drift points: "12 345" vs "12,345").
export function getLocale() { return LOCALES[current] || 'en-GB'; }

export function t(key, params) {
  let s = STRINGS[current][key] ?? STRINGS.hu[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
  return s;
}

export function onLanguageChange(fn) { listeners.push(fn); }

// Translates every element marked with data-i18n* attributes under `root`.
export function applyTranslations(root = document) {
  document.documentElement.lang = current;
  document.title = t('page.title');
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
}

export function setLanguage(lang) {
  if (!LANGUAGES.includes(lang)) return;
  current = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* ignore */ }
  applyTranslations();
  for (const fn of listeners) fn(lang);
}
